/**
 * Fills public/genres.json (artist -> Deezer genre) for every artist listed in data/genre-queue.txt,
 * then empties the queue. Run by the "Update genres" GitHub Action; locally: npx tsx scripts/update-genres.ts
 *
 * Artists Deezer doesn't know are stored as null so they aren't looked up again.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { albumSearchUrl, pickGenre, type DzAlbum } from '../src/lib/genre-core';

const GENRES_FILE = 'public/genres.json';
const QUEUE_FILE = 'data/genre-queue.txt';
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

interface GenreFile {
  about: string;
  genres: Record<string, string | null>;
}

async function lookup(artist: string): Promise<string | null> {
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const res = await fetch(albumSearchUrl(artist));
      const body = (await res.json()) as { data?: DzAlbum[]; error?: { code?: number } };
      if (body.error) throw new Error(`Deezer error ${body.error.code}`); // code 4 = too many requests
      return pickGenre(body.data ?? [], artist);
    } catch (e) {
      console.warn(`  retrying ${artist}: ${(e as Error).message}`);
      await sleep(2000 * (attempt + 1));
    }
  }
  throw new Error(`Gave up on ${artist}`);
}

async function main() {
  const file: GenreFile = existsSync(GENRES_FILE)
    ? JSON.parse(readFileSync(GENRES_FILE, 'utf8'))
    : { about: '', genres: {} };
  const queue = existsSync(QUEUE_FILE)
    ? [...new Set(readFileSync(QUEUE_FILE, 'utf8').split('\n').map((l) => l.trim()).filter(Boolean))]
    : [];
  const todo = queue.filter((a) => !(a in file.genres));
  console.log(`${queue.length} queued, ${todo.length} not yet known`);

  let found = 0;
  try {
    for (const [i, artist] of todo.entries()) {
      const g = await lookup(artist);
      file.genres[artist] = g;
      if (g) found++;
      if ((i + 1) % 100 === 0) console.log(`  ${i + 1}/${todo.length}`);
      await sleep(120); // Deezer allows about 50 requests per 5 seconds
    }
  } finally {
    // Save progress even if we stop early; the remaining artists stay queued.
    const sorted = Object.fromEntries(Object.entries(file.genres).sort(([a], [b]) => a.localeCompare(b)));
    const out: GenreFile = {
      about:
        'Artist -> Deezer genre, read by the app before it looks anything up live. null = Deezer has no genre for them. Generated by scripts/update-genres.ts.',
      genres: sorted,
    };
    writeFileSync(GENRES_FILE, JSON.stringify(out, null, 0).replace(/,"/g, ',\n"') + '\n');
    const left = queue.filter((a) => !(a in sorted));
    writeFileSync(QUEUE_FILE, left.length ? left.join('\n') + '\n' : '');
    console.log(`Found genres for ${found} of ${todo.length}; ${left.length} left in queue`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
