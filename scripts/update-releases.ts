/**
 * Fills public/releases.json (artist -> album -> year first released) for every album listed in
 * data/release-queue.txt (one "artist<TAB>album" per line), then removes them from the queue.
 * Run by the "Update release years" GitHub Action; locally: npx tsx scripts/update-releases.ts
 *
 * Albums neither MusicBrainz nor Deezer knows are stored as null so they aren't looked up again.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { lookupYear, type ReleaseFile } from '../src/lib/release-core';

const RELEASES_FILE = 'public/releases.json';
const QUEUE_FILE = 'data/release-queue.txt';
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
/** Stop and save after this long; whatever is left stays queued for the next round. */
const BUDGET_MS = Number(process.env.RELEASE_BUDGET_MINUTES ?? 20) * 60_000;
// MusicBrainz asks for at most one request per second and a User-Agent that says who is calling.
const USER_AGENT = 'spotify-stats/1.0 ( https://github.com/teddybknox/spotify_stats )';
const GAP: Record<string, number> = { 'musicbrainz.org': 1100, 'api.deezer.com': 120 };
const lastCall: Record<string, number> = {};

async function getJson(url: string): Promise<unknown> {
  const host = new URL(url).host;
  const wait = (lastCall[host] ?? 0) + (GAP[host] ?? 0) - Date.now();
  if (wait > 0) await sleep(wait);
  lastCall[host] = Date.now();
  const res = await fetch(url, { headers: { 'User-Agent': USER_AGENT, Accept: 'application/json' } });
  if (res.status === 503 || res.status === 429) throw new Error(`${host} busy (${res.status})`);
  if (!res.ok) throw new Error(`${host} HTTP ${res.status}`);
  return res.json();
}

async function lookup(artist: string, album: string) {
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      return await lookupYear(artist, album, getJson);
    } catch (e) {
      console.warn(`  retrying ${artist} / ${album}: ${(e as Error).message}`);
      await sleep(3000 * (attempt + 1));
    }
  }
  return undefined; // give up for now; it stays queued
}

const known = (f: ReleaseFile, artist: string, album: string) => f.years[artist] !== undefined && album in f.years[artist];

async function main() {
  const file: ReleaseFile = existsSync(RELEASES_FILE)
    ? JSON.parse(readFileSync(RELEASES_FILE, 'utf8'))
    : { about: '', years: {} };
  const lines = existsSync(QUEUE_FILE) ? readFileSync(QUEUE_FILE, 'utf8').split('\n').filter((l) => l.includes('\t')) : [];
  const queue = [...new Set(lines)].map((l) => l.split('\t') as [string, string]);
  const todo = queue.filter(([a, b]) => !known(file, a, b));
  console.log(`${queue.length} queued, ${todo.length} not yet known`);

  const counts = { musicbrainz: 0, deezer: 0, none: 0, failed: 0 };
  const start = Date.now();
  try {
    for (const [i, [artist, album]] of todo.entries()) {
      if (Date.now() - start > BUDGET_MS) {
        console.log(`Time budget used up after ${i} lookups`);
        break;
      }
      const r = await lookup(artist, album);
      if (!r) {
        counts.failed++;
        continue;
      }
      (file.years[artist] ??= {})[album] = r.year;
      counts[r.source ?? 'none']++;
      if ((i + 1) % 100 === 0) console.log(`  ${i + 1}/${todo.length}`, counts);
    }
  } finally {
    // Save progress even if we stop early; the remaining albums stay queued.
    const years = Object.fromEntries(
      Object.entries(file.years)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([artist, albums]) => [artist, Object.fromEntries(Object.entries(albums).sort(([a], [b]) => a.localeCompare(b)))]),
    );
    const out: ReleaseFile = {
      about:
        'Artist -> album -> year first released, read by the app before it looks anything up live. null = not found. From MusicBrainz, else Deezer. Generated by scripts/update-releases.ts.',
      years,
    };
    // One artist per line keeps the file's history readable.
    const body = Object.entries(years).map(([a, albums]) => `${JSON.stringify(a)}:${JSON.stringify(albums)}`);
    writeFileSync(RELEASES_FILE, `{"about":${JSON.stringify(out.about)},\n"years":{\n${body.join(',\n')}\n}}\n`);
    const left = queue.filter(([a, b]) => !known(out, a, b)).map(([a, b]) => `${a}\t${b}`);
    writeFileSync(QUEUE_FILE, left.length ? left.join('\n') + '\n' : '');
    console.log(`Done: ${JSON.stringify(counts)}; ${left.length} left in queue`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
